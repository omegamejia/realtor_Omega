#!/usr/bin/env node
/**
 * Writes docs/SHOT-LIST.md from the sample photo registry.
 *
 * Every photo frame on the preview is filled from content/sample-media.json,
 * and every entry there carries a `need`: what the REAL photograph has to show.
 * This turns that registry into the list the team shoots from, grouped by page,
 * with the stand-in it replaces so they can see the framing that was intended.
 *
 *   npm run shot-list
 *
 * Re-run it whenever the registry changes. A slot is done when its `src` points
 * at a real file under public/images/ instead of a sample host.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "content/sample-media.json"), "utf8"));
const ts = fs.readFileSync(path.join(root, "content/sample-media.ts"), "utf8");

const SAMPLE_HOSTS = ["upload.wikimedia.org", "thumb.wikimedia.org", "assets.mixkit.co", "/images/samples/"];
const isSample = (src = "") => SAMPLE_HOSTS.some((h) => src.includes(h));

const GROUPS = [
  ["home", "Homepage"],
  ["page", "Page headers"],
  ["area", "Neighborhoods"],
  ["niche", "Situations (seller and buyer pages)"],
];

const slots = (manifest.slots ?? []).filter((s) => s.key);
const lines = [
  "# Shot list",
  "",
  "Generated by `npm run shot-list` from `content/sample-media.json`. Do not edit by hand.",
  "",
  "Every photo on the preview that is not the team's own is a **stand-in**. This is what",
  "each one should become. The launch gate will not pass while any stand-in is still on a page.",
  "",
  "**How to replace one:** drop the real photo in `public/images/` (landscape, 1920px wide or",
  "more), point that slot's `src` at it, and re-run this list.",
  "",
];

let open = 0;
for (const [prefix, title] of GROUPS) {
  const group = slots.filter((s) => s.key.split(".")[0] === prefix);
  if (!group.length) continue;
  lines.push(`## ${title}`, "", "| Slot | What to shoot | Stand-in now | Status |", "|---|---|---|---|");
  for (const s of group) {
    const sample = isSample(s.src);
    if (sample) open++;
    const standIn = sample
      ? `[${(s.title ?? "sample").replace(/\|/g, "/").slice(0, 60)}](${s.original ?? s.src})`
      : "—";
    lines.push(
      `| \`${s.key}\` | ${(s.need ?? "").replace(/\|/g, "/")} | ${standIn} | ${sample ? "needed" : "done"} |`
    );
  }
  lines.push("");
}

// Video needs live beside the video entries in sample-media.ts.
const videos = [...ts.matchAll(/(\w+):\s*\{\s*src:\s*"([^"]+)"[\s\S]*?need:\s*"([^"]+)"/g)];
if (videos.length) {
  lines.push("## Video", "", "| Slot | What to shoot | Status |", "|---|---|---|");
  for (const [, key, src, need] of videos) {
    const sample = isSample(src);
    if (sample) open++;
    lines.push(`| \`video.${key}\` | ${need} | ${sample ? "needed" : "done"} |`);
  }
  lines.push("");
}

lines.splice(4, 0, `**${open} still needed.**`, "");
fs.mkdirSync(path.join(root, "docs"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/SHOT-LIST.md"), lines.join("\n"));
console.log(`docs/SHOT-LIST.md written: ${slots.length} photo slots, ${videos.length} videos, ${open} still needed.`);
